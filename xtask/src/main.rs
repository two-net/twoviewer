//! Development tasks, run as `cargo xtask <command>`:
//!
//! - `new-migration <name>` generates a migration from the changes to the code model (DB-03).
//! - `check-migrations` fails if the migrations and the code model differ (MNT-05).
//!
//! Both work on a throwaway PostgreSQL container, so they need Docker.

use std::{
    env, fs,
    path::PathBuf,
    process::ExitCode,
    sync::{Arc, Mutex},
};

use anyhow::{Context, Result, bail};
use chrono::Utc;
use sqlx::{AssertSqlSafe, Connection, PgConnection};
use testcontainers_modules::{
    postgres::Postgres,
    testcontainers::{ContainerAsync, ImageExt, runners::AsyncRunner},
};
use twoviewer_server::db::{self, migrate::Migration};

const POSTGRES_TAG: &str = "18-alpine";

const USAGE: &str = "usage: cargo xtask new-migration <snake_case_name>
       cargo xtask check-migrations";

#[tokio::main]
async fn main() -> ExitCode {
    let args: Vec<String> = env::args().skip(1).collect();
    let result = match args.iter().map(String::as_str).collect::<Vec<_>>()[..] {
        ["new-migration", name] => new_migration(name).await,
        ["check-migrations"] => check_migrations().await,
        _ => {
            eprintln!("{USAGE}");
            return ExitCode::FAILURE;
        }
    };
    match result {
        Ok(code) => code,
        Err(err) => {
            eprintln!("error: {err:#}");
            ExitCode::FAILURE
        }
    }
}

async fn new_migration(name: &str) -> Result<ExitCode> {
    if name.is_empty()
        || !name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
    {
        bail!("the migration name must be snake_case, for example add_device");
    }
    let mut files = load_migrations()?;
    let id = format!("{}_{name}", Utc::now().format("%Y%m%d%H%M%S"));
    if let Some((last, _)) = files.last()
        && id.as_str() <= last.as_str()
    {
        bail!("{id} would not sort after the newest migration {last}");
    }

    let postgres = Scratch::start().await?;
    let statements =
        model_changes(&migrated_database(&postgres, "generate", &files).await?).await?;
    let sql = render(&statements);
    files.push((id.clone(), sql.clone()));
    let differences = differences(&postgres, &files).await?;

    if statements.is_empty() && differences.is_empty() {
        println!("The migrations already match the code model; nothing to generate.");
        return Ok(ExitCode::SUCCESS);
    }
    let path = migrations_dir().join(format!("{id}.sql"));
    fs::write(&path, sql).with_context(|| format!("write {}", path.display()))?;
    println!("Wrote {}", path.display());

    if differences.is_empty() {
        return Ok(ExitCode::SUCCESS);
    }
    eprintln!(
        "\nSchema sync only adds tables, columns, unique keys and foreign keys. Write the remaining \
         changes by hand at the end of the migration (DB-04), then run `cargo xtask check-migrations`:"
    );
    print_differences(&differences);
    Ok(ExitCode::FAILURE)
}

async fn check_migrations() -> Result<ExitCode> {
    let files = load_migrations()?;
    let postgres = Scratch::start().await?;
    let differences = differences(&postgres, &files).await?;
    if differences.is_empty() {
        println!("The migrations match the code model.");
        return Ok(ExitCode::SUCCESS);
    }
    eprintln!("The migrations and the code model differ. Run `cargo xtask new-migration <name>`:");
    print_differences(&differences);
    Ok(ExitCode::FAILURE)
}

fn render(statements: &[String]) -> String {
    let mut sql = String::from(
        "-- Generated by `cargo xtask new-migration` from the code model. Review it before committing.\n\
         -- Once applied, a migration must not change: correct mistakes with a new migration (DB-12).\n\n",
    );
    for statement in statements {
        sql += statement;
        sql += ";\n";
    }
    sql += "\n-- Hand-written steps (DB-04): only what the ORM cannot express, each with a comment saying why.\n";
    sql
}

/// The DDL that schema sync runs to bring the database at `url` in line with the code model.
async fn model_changes(url: &str) -> Result<Vec<String>> {
    let statements = Arc::new(Mutex::new(Vec::new()));
    let mut db = db::connect(url).await?;
    let captured = Arc::clone(&statements);
    db.set_metric_callback(move |info| {
        let sql = info.statement.to_string();
        // Sync also runs queries to discover the current schema; keep only the changes.
        let keyword = sql
            .split_whitespace()
            .next()
            .unwrap_or_default()
            .to_ascii_uppercase();
        if matches!(keyword.as_str(), "CREATE" | "ALTER" | "DROP" | "COMMENT") {
            captured.lock().unwrap().push(sql);
        }
    });
    db::schema_builder()
        .sync(&db)
        .await
        .context("schema sync")?;
    db.close().await?;
    Ok(std::mem::take(&mut *statements.lock().unwrap()))
}

/// Schema differences between a database built by the migrations and one built from the code
/// model, as `-` (migrations only) and `+` (model only) lines.
async fn differences(postgres: &Scratch, files: &[(String, String)]) -> Result<Vec<String>> {
    let migrated = catalog(&migrated_database(postgres, "migrated", files).await?).await?;

    let url = postgres.create_database("model").await?;
    let db = db::connect(&url).await?;
    db::schema_builder()
        .apply(&db)
        .await
        .context("create the schema from the code model")?;
    db.close().await?;
    let model = catalog(&url).await?;

    let only_migrated = migrated
        .iter()
        .filter(|line| !model.contains(line))
        .map(|line| format!("- {line}"));
    let only_model = model
        .iter()
        .filter(|line| !migrated.contains(line))
        .map(|line| format!("+ {line}"));
    Ok(only_migrated.chain(only_model).collect())
}

fn print_differences(differences: &[String]) {
    for line in differences {
        eprintln!("  {line}");
    }
}

/// The parts of the schema the code model describes, one sorted line each. Constraint and index
/// names are left out, and unique constraints are compared through their indexes, because sync
/// and a fresh `CREATE TABLE` name and declare them differently. Triggers, functions and grants
/// are not compared: they are hand-written (DB-04).
const CATALOG: &str = r"
SELECT format('column %s.%s %s%s%s%s', c.relname, a.attname, format_type(a.atttypid, a.atttypmod),
              CASE WHEN a.attnotnull THEN ' not null' ELSE '' END,
              CASE a.attidentity WHEN 'a' THEN ' generated always as identity'
                                 WHEN 'd' THEN ' generated by default as identity' ELSE '' END,
              coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), ''))
FROM pg_attribute a
JOIN pg_class c ON c.oid = a.attrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE n.nspname = current_schema() AND c.relkind IN ('r', 'p') AND a.attnum > 0 AND NOT a.attisdropped
UNION ALL
SELECT format('constraint %s %s', c.relname, pg_get_constraintdef(k.oid))
FROM pg_constraint k
JOIN pg_class c ON c.oid = k.conrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = current_schema() AND k.contype IN ('p', 'f', 'c', 'x')
UNION ALL
SELECT format('index %s %s', i.tablename,
              regexp_replace(i.indexdef, '^CREATE (UNIQUE )?INDEX \S+ ON ', 'CREATE \1INDEX ON '))
FROM pg_indexes i
WHERE i.schemaname = current_schema()
UNION ALL
SELECT format('enum %s (%s)', t.typname, string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder))
FROM pg_type t
JOIN pg_enum e ON e.enumtypid = t.oid
JOIN pg_namespace n ON n.oid = t.typnamespace
WHERE n.nspname = current_schema()
GROUP BY t.typname
ORDER BY 1
";

async fn catalog(url: &str) -> Result<Vec<String>> {
    let mut conn = PgConnection::connect(url).await?;
    let lines = sqlx::query_scalar(CATALOG).fetch_all(&mut conn).await?;
    conn.close().await?;
    Ok(lines)
}

/// Creates the database `name` and applies `files` to it with the server's migration runner.
async fn migrated_database(
    postgres: &Scratch,
    name: &str,
    files: &[(String, String)],
) -> Result<String> {
    let url = postgres.create_database(name).await?;
    let migrations: Vec<_> = files
        .iter()
        .map(|(id, sql)| Migration { id, sql })
        .collect();
    db::migrate::run(&url, &migrations, "xtask").await?;
    Ok(url)
}

fn migrations_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .join("server/migrations")
}

/// `(id, sql)` of the migrations on disk, in order. They are read from disk, not taken from the
/// server build, so a migration written by this run is included.
fn load_migrations() -> Result<Vec<(String, String)>> {
    let dir = migrations_dir();
    let mut files = Vec::new();
    for entry in fs::read_dir(&dir).with_context(|| format!("read {}", dir.display()))? {
        let path = entry?.path();
        if path.extension().is_some_and(|ext| ext == "sql") {
            let id = path
                .file_stem()
                .and_then(|stem| stem.to_str())
                .context("migration file name")?;
            files.push((id.to_owned(), fs::read_to_string(&path)?));
        }
    }
    files.sort();
    Ok(files)
}

/// A throwaway PostgreSQL server, removed when dropped.
struct Scratch {
    _container: ContainerAsync<Postgres>,
    url: String,
}

impl Scratch {
    async fn start() -> Result<Self> {
        let container = Postgres::default()
            .with_tag(POSTGRES_TAG)
            .start()
            .await
            .context("start a PostgreSQL container (is Docker running?)")?;
        let url = format!(
            "postgres://postgres:postgres@{}:{}",
            container.get_host().await?,
            container.get_host_port_ipv4(5432).await?
        );
        Ok(Self {
            _container: container,
            url,
        })
    }

    /// Creates an empty database and returns its URL.
    async fn create_database(&self, name: &str) -> Result<String> {
        let mut conn = PgConnection::connect(&format!("{}/postgres", self.url)).await?;
        #[expect(
            clippy::disallowed_methods,
            reason = "the database names are constants in this file"
        )]
        sqlx::raw_sql(AssertSqlSafe(format!("CREATE DATABASE {name}")))
            .execute(&mut conn)
            .await?;
        conn.close().await?;
        Ok(format!("{}/{name}", self.url))
    }
}
